app.get('/api/health', asyncHandler(async (req, res) => {
  await pool.query('SELECT 1');
  return res.json({ ok: true, service: 'UniRent API', database: 'connected' });
}));

app.post('/api/auth/signup', asyncHandler(async (req, res) => {
  const name = String(req.body?.name || '').trim();
  const email = String(req.body?.email || '').trim().toLowerCase();
  const password = String(req.body?.password || '');
  const college = String(req.body?.college || '').trim();
  if (name.length < 2 || !/^\S+@\S+\.\S+$/.test(email) || password.length < 6 || college.length < 2) {
    return res.status(400).json({ error: 'Enter your name, valid email, college and a password of at least 6 characters.' });
  }
  try {
    const result = await pool.query(
      'INSERT INTO users(name,email,password_hash,college) VALUES($1,$2,$3,$4) RETURNING id',
      [name, email, bcrypt.hashSync(password, 10), college]
    );
    const user = { id: Number(result.rows[0].id), name, email, college };
    const token = jwt.sign(user, SECRET, { expiresIn: '7d' });
    return res.status(201).json({ token, user });
  } catch (err) {
    if (err.code === '23505') return res.status(409).json({ error: 'That email is already registered.' });
    throw err;
  }
}));

app.post('/api/auth/login', asyncHandler(async (req, res) => {
  const email = String(req.body?.email || '').trim().toLowerCase();
  const password = String(req.body?.password || '');
  const result = await pool.query('SELECT * FROM users WHERE email=$1', [email]);
  const row = result.rows[0];
  if (!row || !bcrypt.compareSync(password, row.password_hash)) return res.status(401).json({ error: 'Email or password is incorrect.' });
  const user = publicUser(row);
  return res.json({ token: jwt.sign(user, SECRET, { expiresIn: '7d' }), user });
}));

app.get('/api/me', auth, asyncHandler(async (req, res) => {
  const result = await pool.query('SELECT id,name,email,college FROM users WHERE id=$1', [req.user.id]);
  if (!result.rows[0]) return res.status(404).json({ error: 'Account not found.' });
  return res.json({ user: publicUser(result.rows[0]) });
}));

app.get('/api/items', asyncHandler(async (req, res) => {
  const result = await pool.query(
    'SELECT items.*, users.name AS owner FROM items JOIN users ON users.id=items.owner_id ORDER BY items.id DESC'
  );
  return res.json({ items: result.rows.map(publicItem) });
}));

app.post('/api/items', auth, asyncHandler(async (req, res) => {
  const title = String(req.body?.title || '').trim();
  const category = String(req.body?.category || '').trim();
  const allowedCategories = new Set(['Books', 'Calculators', 'Electronics', 'Lab equipment', 'Cycles', 'Sports', 'Other']);
  const price = Number(req.body?.price);
  const emoji = String(req.body?.emoji || '📦');
  const image = String(req.body?.image || '');
  const location = String(req.body?.location || 'Campus pickup').trim();
  const desc = String(req.body?.desc || '').trim();
  if (title.length < 2 || !allowedCategories.has(category) || !Number.isFinite(price) || price < 1) {
    return res.status(400).json({ error: 'Enter an item name, valid category and daily price of at least ₹1.' });
  }
  if (image && !/^data:image\/(png|jpe?g|webp|gif);base64,/i.test(image)) {
    return res.status(400).json({ error: 'Upload an image file in PNG, JPG, WEBP or GIF format.' });
  }
  if (image.length > 2_500_000) return res.status(413).json({ error: 'Image is too large. Choose a smaller image (maximum about 1.5 MB).' });
  const result = await pool.query(
    `INSERT INTO items(title,category,price,emoji,image,owner_id,location,description)
     VALUES($1,$2,$3,$4,$5,$6,$7,$8) RETURNING *`,
    [title, category, price, emoji, image, req.user.id, location, desc]
  );
  const row = result.rows[0];
  const owner = await pool.query('SELECT name FROM users WHERE id=$1', [row.owner_id]);
  return res.status(201).json({ item: publicItem({ ...row, owner: owner.rows[0]?.name || 'Student' }) });
}));

app.delete('/api/items/:id', auth, asyncHandler(async (req, res) => {
  const id = Number(req.params.id);
  if (!Number.isSafeInteger(id) || id <= 0) return res.status(400).json({ error: 'Invalid listing ID.' });
  const result = await pool.query('DELETE FROM items WHERE id=$1 AND owner_id=$2 RETURNING id', [id, req.user.id]);
  if (result.rowCount === 0) {
    const exists = await pool.query('SELECT id FROM items WHERE id=$1', [id]);
    if (!exists.rows[0]) return res.status(404).json({ error: 'Listing not found.' });
    return res.status(403).json({ error: 'Only the owner can remove this listing.' });
  }
  return res.json({ ok: true });
}));

app.get('/api/bookings', auth, asyncHandler(async (req, res) => {
  const result = await pool.query(`
    SELECT b.*, i.title, i.price, owner.name AS owner, renter.name AS renter
    FROM bookings b JOIN items i ON i.id=b.item_id
    JOIN users owner ON owner.id=i.owner_id
    JOIN users renter ON renter.id=b.renter_id
    WHERE b.renter_id=$1 ORDER BY b.id DESC
  `, [req.user.id]);
  return res.json({ bookings: result.rows.map(mapBooking) });
}));

app.post('/api/bookings', auth, asyncHandler(async (req, res) => {
  const itemId = Number(req.body?.itemId);
  const from = req.body?.from;
  const to = req.body?.to;
  const message = String(req.body?.message || '').trim().slice(0, 1000);
  if (!Number.isSafeInteger(itemId) || itemId <= 0) return res.status(400).json({ error: 'Choose a valid listing.' });
  const itemResult = await pool.query('SELECT * FROM items WHERE id=$1', [itemId]);
  const item = itemResult.rows[0];
  if (!item) return res.status(404).json({ error: 'This listing is not in the database. Refresh the website and try again.' });
  if (Number(item.owner_id) === req.user.id) return res.status(400).json({ error: 'You cannot book your own item.' });
  if (!validDate(from) || !validDate(to) || to < from) return res.status(400).json({ error: 'Choose valid pickup and return dates.' });
  const days = Math.round((Date.parse(`${to}T00:00:00Z`) - Date.parse(`${from}T00:00:00Z`)) / 86400000) + 1;
  if (!Number.isInteger(days) || days < 1 || days > 365) return res.status(400).json({ error: 'Booking duration must be between 1 and 365 days.' });
  const total = days * Number(item.price);
  const inserted = await pool.query(
    `INSERT INTO bookings(item_id,renter_id,start_date,end_date,days,total,message)
     VALUES($1,$2,$3,$4,$5,$6,$7) RETURNING id`,
    [itemId, req.user.id, from, to, days, total, message]
  );
  const result = await pool.query(`
    SELECT b.*, i.title, i.price, owner.name AS owner, renter.name AS renter
    FROM bookings b JOIN items i ON i.id=b.item_id
    JOIN users owner ON owner.id=i.owner_id
    JOIN users renter ON renter.id=b.renter_id WHERE b.id=$1
  `, [inserted.rows[0].id]);
  return res.status(201).json({ booking: mapBooking(result.rows[0]) });
}));

app.get('/api/wishlist', auth, asyncHandler(async (req, res) => {
  const result = await pool.query('SELECT item_id FROM wishlist WHERE user_id=$1 ORDER BY created_at DESC', [req.user.id]);
  return res.json({ ids: result.rows.map(row => Number(row.item_id)) });
}));

app.post('/api/wishlist/:id', auth, asyncHandler(async (req, res) => {
  const id = Number(req.params.id);
  if (!Number.isSafeInteger(id) || id <= 0) return res.status(404).json({ error: 'Listing not found.' });
  const item = await pool.query('SELECT id FROM items WHERE id=$1', [id]);
  if (!item.rows[0]) return res.status(404).json({ error: 'Listing not found.' });
  await pool.query('INSERT INTO wishlist(user_id,item_id) VALUES($1,$2) ON CONFLICT(user_id,item_id) DO NOTHING', [req.user.id, id]);
  return res.json({ ok: true });
}));

app.delete('/api/wishlist/:id', auth, asyncHandler(async (req, res) => {
  await pool.query('DELETE FROM wishlist WHERE user_id=$1 AND item_id=$2', [req.user.id, Number(req.params.id)]);
  return res.json({ ok: true });
}));

app.use('/api', (req, res) => res.status(404).json({ error: 'API endpoint not found.' }));
app.get('*', (req, res) => res.sendFile(path.join(__dirname, 'unirent', 'index.html')));
app.use((err, req, res, next) => {
  console.error('Request error:', err.message);
  if (res.headersSent) return next(err);
  return res.status(err.status || 500).json({ error: err.status === 413 ? 'Request is too large.' : 'Unexpected server error.' });
});

let server;
async function start() {
  try {
    await initializeDatabase();
    server = app.listen(PORT, '0.0.0.0', () => console.log(`UniRent running on port ${PORT}; PostgreSQL connected.`));
  } catch (err) {
    console.error('UniRent could not start:', err.message);
    process.exit(1);
  }
}
async function shutdown() {
  if (server) server.close();
  await pool.end();
  process.exit(0);
}
process.on('SIGINT', shutdown);
process.on('SIGTERM', shutdown);
start();
